#!/usr/bin/env python3
"""Regression ledger: which fixed bugs have no test guarding them.

Walks the last N commits (default 200), keeps the fix commits (subject
starts with `fix(`, `fix:` or `revert`), and records whether each one also
added or changed a test (Tests/*Tests.swift or Tests/Golden/). Fixes that
shipped without one, and that scripts/regression-ledger.guards doesn't mark
as guarded since or obsolete, are grouped by the source file they changed:
the files at the top are where a refactor is most likely to bring back a
bug that was already fixed once, with every test green.

    scripts/regression-ledger.py                  # markdown to stdout
    scripts/regression-ledger.py --out docs/regression-ledger.md

Read-only: runs `git log` / `git show` and nothing else.
"""

import argparse
import collections
import os
import re
import subprocess
import sys

FIX = re.compile(r"^(fix[(:!]|revert[(:]|Revert )", re.IGNORECASE)
TEST = re.compile(r"^Tests/(.*Tests\.swift|Golden/)")
# Files whose fixes rank. Docs, examples and scripts still show in the
# per-commit table.
CODE = re.compile(r"^(Sources/.*\.(swift|c|m|h)|Runtime/src/.*\.js|build\.sh|tests\.sh)$")
GUARDS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "regression-ledger.guards")


def git(*args):
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout


def fix_commits(n):
    out = []
    for line in git("log", f"-{n}", "--no-merges", "--format=%h%x09%ad%x09%s", "--date=short").splitlines():
        sha, date, subject = line.split("\t", 2)
        if FIX.match(subject):
            files = [f for f in git("show", "--name-only", "--format=", sha).splitlines() if f]
            out.append((sha, date, subject, files))
    return out


def load_guards():
    guards = {}
    if os.path.exists(GUARDS):
        for line in open(GUARDS):
            if line.strip() and not line.startswith("#"):
                sha, status, what = line.rstrip("\n").split("\t", 2)
                guards[sha] = (status, what)
    return guards


def test_files_for(path, tests):
    """Test files named after the source file (Overlay.swift ->
    OverlayTests, OverlayGeometryTests, ...). A name match is a hint only."""
    stem = os.path.splitext(os.path.basename(path))[0]
    stem = re.sub(r"^Bridge(?=[A-Z])", "", stem)
    stem = re.sub(r"^\d+-", "", stem)
    key = stem.replace("-", "").lower()
    return sorted(t for t in tests if os.path.basename(t).lower().startswith(key))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--commits", type=int, default=200)
    ap.add_argument("--out")
    args = ap.parse_args()

    tests = [f for f in git("ls-files", "Tests").splitlines() if f.endswith("Tests.swift")]
    head = git("rev-parse", "--short", "HEAD").strip()
    guards = load_guards()
    fixes = fix_commits(args.commits)

    unguarded = collections.defaultdict(list)
    tested = collections.Counter()
    rows = []
    for sha, date, subject, files in fixes:
        if any(TEST.match(f) for f in files):
            status = "same-commit test"
        elif sha in guards:
            status = f"{guards[sha][0]}: {guards[sha][1]}"
        else:
            status = "**unguarded**"
        code = [f for f in files if CODE.match(f)]
        for f in code:
            if status == "same-commit test":
                tested[f] += 1
            elif status == "**unguarded**":
                unguarded[f].append(sha)
        rows.append((sha, date, subject, status, code, files))

    counts = collections.Counter(
        "test" if r[3] == "same-commit test" else "unguarded" if r[3] == "**unguarded**" else "later"
        for r in rows)
    lines = [
        "# Regression ledger",
        "",
        f"Generated by `scripts/regression-ledger.py --commits {args.commits}` at `{head}`; "
        "regenerate rather than edit. Hand-kept input: `scripts/regression-ledger.guards`.",
        "",
        f"Last {args.commits} commits: **{len(rows)} fix/revert commits**. "
        f"{counts['test']} shipped a test in the same commit, {counts['later']} are guarded since "
        f"(or their code is gone), **{counts['unguarded']} are unguarded**.",
        "",
        "An unguarded fix is a bug a refactor can bring back with every test green. Files rank by "
        "unguarded fixes; `tested fixes` counts fixes to the same file that did ship a test. "
        "`tests today` lists test files named after the source file, a hint, not proof of coverage.",
        "",
        "## Unguarded fixes by file",
        "",
        "| file | unguarded | tested fixes | tests today | commits |",
        "|---|---:|---:|---|---|",
    ]
    for f, shas in sorted(unguarded.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        today = ", ".join(os.path.basename(t)[:-len(".swift")] for t in test_files_for(f, tests)) or "none"
        lines.append(f"| `{f}` | {len(shas)} | {tested.get(f, 0)} | {today} | "
                     + " ".join(f"`{s}`" for s in shas) + " |")

    lines += ["", "## Every fix commit", "", "| commit | date | guard | subject | code files |", "|---|---|---|---|---|"]
    for sha, date, subject, status, code, files in rows:
        shown = ", ".join(f"`{f}`" for f in code) or "(" + ", ".join(files[:3]) + ")"
        lines.append(f"| `{sha}` | {date} | {status.replace('|', '/')} | {subject.replace('|', '/')} | {shown} |")

    text = "\n".join(lines) + "\n"
    if args.out:
        with open(args.out, "w") as fh:
            fh.write(text)
        print(f"wrote {args.out}: {len(rows)} fixes, {counts['unguarded']} unguarded", file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
