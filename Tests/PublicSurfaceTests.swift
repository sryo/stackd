import Foundation
import JavaScriptCore

// Golden snapshot of everything a stack, the CLI or the bench can observe of
// the daemon: permissions, channels, the primitive table, the `sd` object the
// runtime builds, manifest keys, CLI verbs, bang names, env switches and
// template directives. A refactor that drops or renames any of them fails
// with a per-section diff. An intentional surface change regenerates the
// golden in the same commit:
//
//   STACKD_UPDATE_GOLDEN=1 ./tests.sh --filter '^surface:'
//
// The cross-checks below the snapshot hold whatever the golden says: both
// halves of the bridge must agree on wire types and callback globals.

/// Committed expected-output files under Tests/Golden/.
enum Golden {
    static let updateCommand = "STACKD_UPDATE_GOLDEN=1 ./tests.sh --filter '^surface:|^stack compat:'"

    static var updating: Bool {
        ProcessInfo.processInfo.environment["STACKD_UPDATE_GOLDEN"] == "1"
    }

    /// Compare `actual` with the golden at `path`. The actual text always
    /// lands in `.build/golden/` so `diff -u` works after a failure; with
    /// STACKD_UPDATE_GOLDEN=1 it overwrites the golden instead.
    static func check(_ actual: String, path: String) throws {
        let actualPath = ".build/golden/" + (path as NSString).lastPathComponent
        try? FileManager.default.createDirectory(atPath: ".build/golden", withIntermediateDirectories: true)
        try? actual.write(toFile: actualPath, atomically: true, encoding: .utf8)
        if updating {
            try actual.write(toFile: path, atomically: true, encoding: .utf8)
            print("  wrote \(path)")
            return
        }
        guard let expected = try? String(contentsOfFile: path, encoding: .utf8) else {
            throw Expectation(message: "missing golden \(path) — create it with: \(updateCommand)")
        }
        if expected == actual { return }
        throw Expectation(message: """
            \(path) drifted from the code:
            \(sectionDiff(expected: expected, actual: actual))
              full diff: diff -u \(path) \(actualPath)
              intentional change? regenerate in the same commit: \(updateCommand)
            """)
    }

    /// Per-section `-`/`+` lines. Sections are `[name]` headers; `#` lines
    /// are commentary and never diffed. A section whose lines are unchanged
    /// but reordered reports that, since some sections (channels) are ordered.
    static func sectionDiff(expected: String, actual: String) -> String {
        func sections(_ text: String) -> [(String, [String])] {
            var out: [(String, [String])] = []
            for line in text.split(separator: "\n", omittingEmptySubsequences: true).map(String.init) {
                if line.hasPrefix("#") { continue }
                if line.hasPrefix("[") { out.append((line, [])); continue }
                if out.isEmpty { out.append(("[]", [])) }
                out[out.count - 1].1.append(line)
            }
            return out
        }
        let exp = sections(expected), act = sections(actual)
        let expMap = Dictionary(exp, uniquingKeysWith: { a, _ in a })
        let actMap = Dictionary(act, uniquingKeysWith: { a, _ in a })
        var names = exp.map { $0.0 }
        for (n, _) in act where !names.contains(n) { names.append(n) }
        var lines: [String] = []
        for name in names {
            let e = expMap[name] ?? [], a = actMap[name] ?? []
            let eSet = Set(e), aSet = Set(a)
            let removed = e.filter { !aSet.contains($0) }
            let added = a.filter { !eSet.contains($0) }
            for l in removed { lines.append("  - \(name) \(l)") }
            for l in added { lines.append("  + \(name) \(l)") }
            if removed.isEmpty && added.isEmpty && e != a { lines.append("  ~ \(name) same entries, different order") }
        }
        return lines.isEmpty ? "  (whitespace-only difference)" : lines.joined(separator: "\n")
    }
}

/// Builders for each section of the public surface. Runtime sections read
/// the live registries; sections marked "source scan" grep the source tree
/// because the daemon has no registry for them.
enum PublicSurface {
    static let goldenPath = "Tests/Golden/public-surface.txt"

    static func render() -> String {
        var out: [String] = [
            "# stackd public surface — generated by Tests/PublicSurfaceTests.swift; do not edit.",
            "# Regenerate only for an intentional change, in the same commit:",
            "#   \(Golden.updateCommand)",
        ]
        func section(_ header: String, _ note: String, _ body: [String]) {
            out.append("")
            out.append(header)
            out.append("# " + note)
            out.append(contentsOf: body)
        }
        section("[permissions]", "Permissions.all; 'explicit' = never inferred from source",
                Permissions.all.sorted().map { Permissions.inferable.contains($0) ? $0 : "\($0) explicit" })
        section("[channels]", "Channels.all in replay order: name js=<sd path> perm=<permission> replay|delta",
                Channels.all.map { "\($0.name) js=\($0.jsPath ?? "-") perm=\($0.permission) \($0.replayable ? "replay" : "delta")" })
        section("[primitives]", "bridge dispatch table: wire type, permission gate, what a denied call resolves to",
                Bridge.primitiveContract.map { "\($0.type) perm=\($0.permission ?? "-") deny=\($0.deny)" })
        section("[runtime]", "window.sd as Runtime/api.js builds it: object | signal | fn/<arity> | value | getter | alias <path>",
                runtimeEntries().map { "\($0.path) \($0.kind)" })
        section("[runtime.globals]", "callbacks the runtime installs for the daemon to call",
                runtimeGlobals())
        section("[overlay.page]", "source scan: window.sd members the daemon injects into overlay pages",
                overlayPageMembers().map { "sd." + $0 })
        section("[page.events]", "source scan: DOM events the daemon or runtime dispatch into pages",
                Array(Set(SourceScan.matches(customEvent, in: "Sources", exts: ["swift"])
                          + SourceScan.matches(customEvent, in: "Runtime/src", exts: ["js"]))).sorted())
        section("[manifest]", "stack.json keys, decoded from a sample that sets every key",
                manifestFields())
        section("[cli]", "verbs `stackd help` lists",
                cliVerbs())
        section("[bangs]", "source scan: \"sd.<ns>.<event>\" literals in Sources/",
                SourceScan.matches(#""(sd\.[A-Za-z]+\.[A-Za-z]+)""#, in: "Sources", exts: ["swift"]))
        section("[env]", "source scan: STACKD_* switches in Sources/",
                SourceScan.matches(#"\b(STACKD_[A-Z0-9_]+)"#, in: "Sources", exts: ["swift"]))
        section("[templates]", "source scan: sd-* directives in Runtime/src/",
                SourceScan.matches(#"["'`](sd-[a-z:-]+)"#, in: "Runtime/src", exts: ["js"]))
        return out.joined(separator: "\n") + "\n"
    }

    // MARK: runtime (window.sd)

    struct Entry { let path: String; let kind: String }

    /// Its own context, so the snapshot doesn't depend on what earlier tests
    /// installed in the shared one. Read-only after load.
    private static let runtime: JSContext? = JSHarness.makeContext()

    /// Walks `sd` without invoking getters or functions. Signals report only
    /// the members added on top of value/subscribe/peek/first (sd.mouse.warp).
    static func runtimeEntries() -> [Entry] {
        let js = """
        (function () {
          const out = [];
          const seen = new Map();
          const isObj = v => v !== null && (typeof v === 'object' || typeof v === 'function');
          const isSignal = v => isObj(v) && typeof v.subscribe === 'function' && typeof v.peek === 'function';
          const signalBase = new Set(['value', 'subscribe', 'peek', 'first']);
          function walk(v, path, depth) {
            if (isObj(v) && seen.has(v)) { out.push(path + '\\talias ' + seen.get(v)); return; }
            if (isObj(v)) seen.set(v, path);
            const signal = isSignal(v);
            const kind = signal ? 'signal'
              : typeof v === 'function' ? 'fn/' + v.length
              : isObj(v) ? 'object' : 'value';
            out.push(path + '\\t' + kind);
            if (!isObj(v) || depth >= 6) return;
            const keys = (typeof v === 'function' ? Object.keys(v) : Object.getOwnPropertyNames(v)).sort();
            for (const k of keys) {
              if (signal && signalBase.has(k)) continue;
              const d = Object.getOwnPropertyDescriptor(v, k);
              if (d && d.get) { out.push(path + '.' + k + '\\tgetter'); continue; }
              walk(v[k], path + '.' + k, depth + 1);
            }
          }
          walk(globalThis.sd, 'sd', 0);
          return out.join('\\n');
        })()
        """
        guard let text = runtime?.evaluateScript(js)?.toString() else { return [] }
        return text.split(separator: "\n").compactMap { line in
            let parts = line.split(separator: "\t", maxSplits: 1).map(String.init)
            return parts.count == 2 ? Entry(path: parts[0], kind: parts[1]) : nil
        }
    }

    private static let customEvent = #"CustomEvent\(\s*['"]([^'"]+)['"]"#

    /// Overlay pages don't load the runtime; the daemon assigns these onto
    /// their `window.sd` (sd.target).
    static func overlayPageMembers() -> [String] {
        SourceScan.matches(#"window\.sd\.([A-Za-z_]+)\s*=[^=]"#, in: "Sources", exts: ["swift"])
    }

    static func runtimeGlobals() -> [String] {
        let js = """
        Object.getOwnPropertyNames(globalThis)
          .filter(k => (k.startsWith('__sd_') || k.startsWith('onBang_')) && typeof globalThis[k] === 'function')
          .sort().join('\\n')
        """
        let text = runtime?.evaluateScript(js)?.toString() ?? ""
        return text.split(separator: "\n").map(String.init)
    }

    // MARK: manifest

    /// Sets every key StackManifest decodes, nested types included. A key
    /// added to StackManifest shows up as `= nil` until it is added here.
    static let sampleManifest = """
    {"id":"sample","name":"Sample",
     "anchor":{"edge":"top-left","inset":[1,2]},
     "region":"menubar",
     "size":{"w":3,"h":4},
     "clickThrough":true,
     "hideDuringScreenshot":false,
     "headless":false,
     "permissions":["battery"],
     "hotkeys":[{"key":"cmd+a","callback":"onA","mode":"m","apps":["com.x"],"excludeApps":["com.y"]}],
     "handles":["sd.window.created"],
     "eventtap":[{"event":"keyDown","callback":"onK","consume":true,"requireRects":true,"emitLeave":true,
                  "if":{"keyCode":5,"keyCodes":[6],"flagsMask":7,"flagsAny":8}}],
     "display":"all",
     "invocable":true,
     "level":"floating",
     "material":"glass",
     "cornerRadius":9,
     "shape":"capsule",
     "padding":10,
     "reset":false}
    """

    static func manifestFields() -> [String] {
        do {
            let m = try JSONDecoder().decode(StackManifest.self, from: Data(sampleManifest.utf8))
            return reflect(m, prefix: "")
        } catch {
            return ["DECODE FAILED: \(error)"]
        }
    }

    private static func reflect(_ value: Any, prefix: String) -> [String] {
        var out: [String] = []
        for child in Mirror(reflecting: value).children {
            guard let label = child.label else { continue }
            out.append(contentsOf: describe(child.value, path: prefix + label))
        }
        return out
    }

    private static func describe(_ value: Any, path: String) -> [String] {
        let m = Mirror(reflecting: value)
        switch m.displayStyle {
        case .optional:
            guard let some = m.children.first?.value else { return ["\(path) = nil"] }
            return describe(some, path: path)
        case .struct:
            return reflect(value, prefix: path + ".")
        case .collection:
            let items = Array(m.children.map { $0.value })
            if let first = items.first, Mirror(reflecting: first).displayStyle == .struct {
                return reflect(first, prefix: path + "[].")
            }
            return ["\(path) = [\(items.map { scalar($0) }.joined(separator: ","))]"]
        default:
            return ["\(path) = \(scalar(value))"]
        }
    }

    private static func scalar(_ v: Any) -> String {
        if let s = v as? String { return "\"\(s)\"" }
        return "\(v)"
    }

    // MARK: cli

    /// First column of the verb table at the top of `CLI.helpText`.
    static func cliVerbs() -> [String] {
        var out: [String] = []
        for line in CLI.helpText.split(separator: "\n", omittingEmptySubsequences: false).dropFirst() {
            let s = String(line)
            if s.trimmingCharacters(in: .whitespaces).isEmpty { break }
            let trimmed = s.trimmingCharacters(in: .whitespaces)
            let verb = trimmed.components(separatedBy: "  ").first ?? trimmed
            out.append(verb.trimmingCharacters(in: .whitespaces))
        }
        return out
    }
}

/// Regex over source files. Line comments (`//`, `*` continuation lines) are
/// skipped so examples in doc comments don't count as code.
enum SourceScan {
    static func files(in dir: String, exts: Set<String>) -> [String] {
        guard let walker = FileManager.default.enumerator(atPath: dir) else { return [] }
        var out: [String] = []
        for case let rel as String in walker where exts.contains((rel as NSString).pathExtension) {
            out.append(dir + "/" + rel)
        }
        return out.sorted()
    }

    static func codeLines(_ path: String) -> [String] {
        guard let text = try? String(contentsOfFile: path, encoding: .utf8) else { return [] }
        return text.components(separatedBy: "\n").filter { line in
            let t = line.trimmingCharacters(in: .whitespaces)
            return !(t.hasPrefix("//") || t.hasPrefix("*") || t.hasPrefix("/*"))
        }
    }

    /// Sorted unique capture-group-1 values of `pattern` across the files.
    static func matches(_ pattern: String, in dir: String, exts: Set<String>) -> [String] {
        guard let re = try? NSRegularExpression(pattern: pattern) else { return [] }
        var found = Set<String>()
        for file in files(in: dir, exts: exts) {
            for line in codeLines(file) {
                let ns = line as NSString
                for m in re.matches(in: line, range: NSRange(location: 0, length: ns.length)) {
                    found.insert(ns.substring(with: m.range(at: 1)))
                }
            }
        }
        return found.sorted()
    }
}

func registerPublicSurfaceTests() {
    test("surface: public surface matches Tests/Golden/public-surface.txt") {
        try Golden.check(PublicSurface.render(), path: PublicSurface.goldenPath)
    }

    test("surface: sample manifest sets every StackManifest key") {
        let unset = PublicSurface.manifestFields().filter { $0.hasSuffix("= nil") || $0.hasPrefix("DECODE FAILED") }
        try expect(unset.isEmpty, "add these keys to PublicSurface.sampleManifest: \(unset)")
    }

    test("surface: every wire type Runtime/src sends is a bridge primitive") {
        let sent = Set(SourceScan.matches(#"\btype:\s*"([A-Za-z0-9_.]+)""#, in: "Runtime/src", exts: ["js"]))
        let handled = Set(Bridge.primitiveContract.map { $0.type })
        let orphaned = sent.subtracting(handled)
        try expect(orphaned.isEmpty, "runtime sends types the bridge drops silently: \(orphaned.sorted())")
    }

    test("surface: every bridge primitive is sent by Runtime/src") {
        let sent = Set(SourceScan.matches(#"\btype:\s*"([A-Za-z0-9_.]+)""#, in: "Runtime/src", exts: ["js"]))
        let unreachable = Set(Bridge.primitiveContract.map { $0.type }).subtracting(sent)
        try expect(unreachable.isEmpty, "primitives no sd.* call reaches: \(unreachable.sorted())")
    }

    test("surface: every __sd_ callback the daemon evaluates is installed by the runtime") {
        let all = Set(SourceScan.matches(#"(__sd_[A-Za-z0-9_]+)"#, in: "Sources", exts: ["swift"]))
        // Globals the daemon assigns (window.__sd_screen = …) are data it
        // injects, not callbacks it expects the runtime to define.
        let injected = Set(SourceScan.matches(#"(__sd_[A-Za-z0-9_]+)\s*=[^=]"#, in: "Sources", exts: ["swift"]))
        let installed = Set(PublicSurface.runtimeGlobals())
        let missing = all.subtracting(injected).subtracting(installed)
        try expect(missing.isEmpty, "daemon calls runtime callbacks that don't exist: \(missing.sorted())")
    }
}
